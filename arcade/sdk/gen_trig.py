"""Writes apps-ipod/games/arcade/core_trig.h: the quarter-wave sine and the
octant arctangent the core's sin, cos and atan2 interpolate. The tables
are integers, so every target computes the same results from them; run
this only to change them, which changes what every cart computes."""

import math
import os

out = os.path.join(os.path.dirname(__file__), '..', '..', 'apps-ipod',
                   'games', 'arcade', 'core_trig.h')

sine = [round(math.sin(i / 1024 * math.pi / 2) * 65536) for i in range(1025)]
atan = [round(math.atan(i / 256) / (2 * math.pi) * 65536) for i in range(257)]


def rows(values):
    lines = []
    for i in range(0, len(values), 8):
        lines.append('    ' + ', '.join(str(v) for v in values[i:i + 8]) + ',')
    return '\n'.join(lines)


with open(out, 'w', newline='\n') as f:
    f.write('/* GNU General Public License (version 2+)\n *\n'
            ' * Generated by arcade/sdk/gen_trig.py; do not edit. */\n\n')
    f.write('/* sin(i / 1024 of a quarter turn), 16.16 */\n')
    f.write('static const int32_t sine_q[1025] = {\n' + rows(sine) + '\n};\n\n')
    f.write('/* atan(i / 256) in 1/65536 turns */\n')
    f.write('static const uint16_t atan_o[257] = {\n' + rows(atan) + '\n};\n')
print('wrote', os.path.normpath(out))
