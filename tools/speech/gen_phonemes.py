#!/usr/bin/env python3
"""Write apps-ipod/speech/synth_phonemes.c from NV Speech Player's data.py.

usage: gen_phonemes.py <data.py> <synth_phonemes.c>

data.py is from github.com/nvaccess/NVSpeechPlayer at e51ee50. Its values
are written as fixed point with 16 fractional bits, rounded, after the
changes in OVERRIDES.
"""
import codecs
import sys

PARAMS = [
    'voicePitch', 'vibratoPitchOffset', 'vibratoSpeed',
    'voiceTurbulenceAmplitude', 'glottalOpenQuotient', 'voiceAmplitude',
    'aspirationAmplitude',
    'cf1', 'cf2', 'cf3', 'cf4', 'cf5', 'cf6', 'cfN0', 'cfNP',
    'cb1', 'cb2', 'cb3', 'cb4', 'cb5', 'cb6', 'cbN0', 'cbNP',
    'caNP', 'fricationAmplitude',
    'pf1', 'pf2', 'pf3', 'pf4', 'pf5', 'pf6',
    'pb1', 'pb2', 'pb3', 'pb4', 'pb5', 'pb6',
    'pa1', 'pa2', 'pa3', 'pa4', 'pa5', 'pa6',
    'parallelBypass', 'preFormantGain', 'outputGain', 'endVoicePitch',
]
FLAGS = {
    '_isNasal': 'PH_NASAL', '_isStop': 'PH_STOP', '_isLiquid': 'PH_LIQUID',
    '_isVowel': 'PH_VOWEL', '_isVoiced': 'PH_VOICED',
    '_isSemivowel': 'PH_SEMIVOWEL', '_isAfricate': 'PH_AFRICATE',
    '_copyAdjacent': 'PH_COPY_ADJACENT',
}

# Chosen by ear. At full voicing v, dh, z and zh are heard as vowels or as
# n; the IPA g (U+0261) is tuned unlike the ASCII g, and sounds less like one.
VOICED_FRICATIVE = {'voiceAmplitude': 0.15, 'cb1': 200.0}
OVERRIDES = {
    'v': VOICED_FRICATIVE, 'ð': VOICED_FRICATIVE,
    'z': VOICED_FRICATIVE, 'ʒ': VOICED_FRICATIVE,
}
SAME_AS = {'ɡ': 'g'}

HEADER = """\
/***************************************************************************
 * GNU General Public License (version 2 only)
 * Port of NV Speech Player, Copyright (C) 2014 NV Access Limited
 *
 * Generated by tools/speech/gen_phonemes.py from NV Speech Player's data.py.
 * Do not edit; change the generator or its input.
 ****************************************************************************/

#include "synth_phonemes.h"

const struct synth_phoneme synth_phonemes[] =
{
"""


def main():
    data = eval(codecs.open(sys.argv[1], 'r', 'utf8').read(), None, None)
    for key, change in OVERRIDES.items():
        data[key].update(change)
    for key, source in SAME_AS.items():
        data[key] = dict(data[source])
    out = [HEADER]
    for key, entry in data.items():
        unknown = [k for k in entry if k not in FLAGS and k not in PARAMS]
        if unknown or len(key) > 3:
            sys.exit("%r: cannot represent %r" % (key, unknown or key))
        codes = [ord(c) for c in key] + [0] * (3 - len(key))
        flags = [FLAGS[k] for k in FLAGS if entry.get(k)]
        present = 0
        values = []
        for i, name in enumerate(PARAMS):
            if name in entry:
                present |= 1 << i
                values.append(str(int(round(entry[name] * 65536))))
            else:
                values.append('0')
        out.append('    { /* %s */\n' % key.encode('unicode_escape').decode())
        out.append('        { %s },\n' % ', '.join('0x%04x' % c for c in codes))
        out.append('        %s,\n' % (' | '.join(flags) or '0'))
        out.append('        0x%016xull,\n' % present)
        out.append('        {\n')
        for i in range(0, len(values), 6):
            out.append('            %s,\n' % ', '.join(values[i:i + 6]))
        out.append('        },\n    },\n')
    used = 0
    for entry in data.values():
        for k in range(6):
            if entry.get('pa%d' % (k + 1)):
                used |= 1 << k
    out.append('};\n\nconst int synth_phoneme_count =\n'
               '    sizeof(synth_phonemes) / sizeof(synth_phonemes[0]);\n')
    out.append('\nconst unsigned int synth_parallel_used = 0x%02x;\n' % used)
    with open(sys.argv[2], 'w', encoding='utf8', newline='\n') as f:
        f.write(''.join(out))


main()
