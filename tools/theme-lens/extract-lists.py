#!/usr/bin/env python3
"""Pull the firmware's real menus out of the build, as list fixtures.

    python extract-lists.py > lists.json
    python extract-lists.py --js            # ready to paste

Run from anywhere: with no argument it reads the checkout it is sitting in,
which is the whole reason the lens lives in the firmware tree. Name a different
checkout to read that one instead.

Laying out a list row against "Row one / Row two / Row three" tells you very
little: real menu text is longer, wraps differently, and carries icon ids your
row layout branches on. This reads the menus the firmware actually builds —
their order, their text, and the icon each item declares — so the preview shows
what the player will.

Three files carry it all:

  apps-ipod/lang/english.lang   LANG_* -> the English string
  apps-ipod/**/*.c              MENUITEM_* items and MAKE_MENU trees
  apps-ipod/settings/*.c        the LANG_* a MENUITEM_SETTING resolves through

Nothing here is compiled or executed — it is a read of the source. Where an
item's text is decided at runtime (MENUITEM_*_DYNTEXT) it is emitted with the
name the firmware gives it and a "dynamic" flag, because a fixture that guesses
would be worse than one that admits it.
"""

